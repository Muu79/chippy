#[derive(Copy, Clone, Default)]
#[repr(u16)]
pub enum Sprite {
    Zero = 0x00,
    One = 0x05,
    Two = 0x0A,
    Three = 0x0F,
    Four = 0x14,
    Five = 0x19,
    Six = 0x1E,
    Seven = 0x23,
    Eight = 0x28,
    Nine = 0x2D,
    A = 0x32,
    B = 0x37,
    C = 0x3C,
    D = 0x41,
    E = 0x46,
    F = 0x4B,
    BigZero = 0x50,
    BigOne = 0x5A,
    BigTwo = 0x64,
    BigThree = 0x6E,
    BigFour = 0x78,
    BigFive = 0x82,
    BigSix = 0x8C,
    BigSeven = 0x96,
    BigEight = 0xA0,
    BigNine = 0xAA,
    BigA = 0xB4,
    BigB = 0xBE,
    BigC = 0xC8,
    BigD = 0xD2,
    BigE = 0xDC,
    BigF = 0xE6,
    #[default]
    Unknown = 0x1FB, // 5 bytes before ROM start, should be blank
}

impl Sprite {
    pub fn from_hex(hex: u8, is_extended: bool) -> Result<Self, &'static str> {
        match hex {
            0x0 => Ok(if is_extended {
                Self::BigZero
            } else {
                Self::Zero
            }),
            0x1 => Ok(if is_extended { Self::BigOne } else { Self::One }),
            0x2 => Ok(if is_extended { Self::BigTwo } else { Self::Two }),
            0x3 => Ok(if is_extended {
                Self::BigThree
            } else {
                Self::Three
            }),
            0x4 => Ok(if is_extended {
                Self::BigFour
            } else {
                Self::Four
            }),
            0x5 => Ok(if is_extended {
                Self::BigFive
            } else {
                Self::Five
            }),
            0x6 => Ok(if is_extended { Self::BigSix } else { Self::Six }),
            0x7 => Ok(if is_extended {
                Self::BigSeven
            } else {
                Self::Seven
            }),
            0x8 => Ok(if is_extended {
                Self::BigEight
            } else {
                Self::Eight
            }),
            0x9 => Ok(if is_extended {
                Self::BigNine
            } else {
                Self::Nine
            }),
            0xA => Ok(if is_extended { Self::BigA } else { Self::A }),
            0xB => Ok(if is_extended { Self::BigB } else { Self::B }),
            0xC => Ok(if is_extended { Self::BigC } else { Self::C }),
            0xD => Ok(if is_extended { Self::BigD } else { Self::D }),
            0xE => Ok(if is_extended { Self::BigE } else { Self::E }),
            0xF => Ok(if is_extended { Self::BigF } else { Self::F }),
            _ => Err("Invalid sprite"),
        }
    }
}

impl From<char> for Sprite {
    fn from(char: char) -> Self {
        match char {
            '0' => Self::Zero,
            '1' => Self::One,
            '2' => Self::Two,
            '3' => Self::Three,
            '4' => Self::Four,
            '5' => Self::Five,
            '6' => Self::Six,
            '7' => Self::Seven,
            '8' => Self::Eight,
            '9' => Self::Nine,
            'a' | 'A' => Self::A,
            'b' | 'B' => Self::B,
            'c' | 'C' => Self::C,
            'd' | 'D' => Self::D,
            'e' | 'E' => Self::E,
            'f' | 'F' => Self::F,
            _ => Self::Unknown,
        }
    }
}